// Usage: bun build-console.mjs
// Bundles the bot, its per-class data files and the panels into ../dist/ombreval-bot.js,
// a single script to paste into the DevTools console of the game tab (no Node, no debug port needed).
import fs from 'fs';

const read = f => fs.readFileSync(new URL('./' + f, import.meta.url), 'utf8');
const json = f => { try { return JSON.parse(read(f)); } catch { return null; } };
// Same per-class files as run.mjs; an unsupported class falls back to the necro files, as there.
const FILES = { necromancer: ['build.json', 'skill_values.json'], shaman: ['shaman_build.json', 'shaman_skills.json'], reaper: ['reaper_build.json', 'reaper_skills.json'] };
const data = Object.fromEntries(Object.entries(FILES).map(([cls, [b, k]]) => [cls, [json(b), json(k)]]));
// Overlays are optional, like in run.mjs: a broken one must not block the bot.
const optional = (f, name) => `try {\nconsole.log(${read(f).trim().replace(/;$/, '')});\n} catch (e) { console.warn('${name} non chargé :', e.message); }`;

const out = `// Ombreval bot, console build (generated by bot/build-console.mjs, do not edit).
// Enter the world with a character, open the console (F12), paste this whole file, press Enter.
// After a page reload or a character switch, paste it again. State: __bot.status(). Stop: __bot.stop().
(() => {
  const g = window.__game;
  if (!g?.inWorld || !g.char) throw new Error('Entrez en jeu avec un personnage, puis collez ce script.');
  const DATA = ${JSON.stringify(data)};
  [window.__botBuild, window.__botSkills] = DATA[g.char.ch.cls] ?? DATA.necromancer;
})();
console.log(${read('bot.page.js').trim().replace(/;$/, '')});
${optional('viz.page.js', 'viz')}
${optional('gather.page.js', 'gather')}
${optional('assist.page.js', 'assist')}
window.__bot.start();
`;

// Written readable first, then minified in place by Bun (smaller paste); the comments above are lost.
const file = new URL('../dist/ombreval-bot.js', import.meta.url).pathname;
fs.mkdirSync(new URL('../dist/', import.meta.url), { recursive: true });
fs.writeFileSync(file, out);
const res = await Bun.build({ entrypoints: [file], minify: true, target: 'browser' });
if (!res.success) throw new AggregateError(res.logs, 'minification échouée');
const min = await res.outputs[0].text();
fs.writeFileSync(file, '// Ombreval bot, console build: https://github.com/naashw/ombreval-bot (paste in the game tab console, in world)\n' + min);
console.log(`dist/ombreval-bot.js : ${(min.length / 1024).toFixed(0)} Ko`);
